package dev.lattenero.bot.transport

import kotlinx.coroutines.test.runTest
import kotlinx.coroutines.test.testTimeSource
import org.junit.jupiter.api.Assumptions.assumeTrue
import org.junit.jupiter.api.io.TempDir
import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertNull
import kotlin.test.assertTrue

/**
 * The outbox (utils/http.py _outbox_*): the FILE CONTRACT is Python's
 * outbox.json verbatim (a JSON array of {"ts": int, "text": str} with
 * json.dumps' ", "/": " separators, ensure_ascii=False — raw UTF-8),
 * capped at 20 entries of CH_REPLY code points, under flock on the
 * .lock sidecar. The verbatim expectations below were generated by
 * running the REAL Python _outbox_put (2026-10-29); the flock waits use
 * a REAL child process holding the POSIX lock — the cross-process
 * contract is the point.
 */
class OutboxTest {

    @TempDir
    lateinit var dir: File

    private val path: File get() = File(dir, "outbox.json")
    private fun outbox(ts: Double = 1_730_200_000.0) = Outbox(path, now = { ts })

    @Test
    fun putWritesPythonsBytes() = runTest {
        outbox().put("hola mundo")
        assertEquals("""[{"ts": 1730200000, "text": "hola mundo"}]""", path.readText(), "the Python bytes, verbatim")
        assertTrue(File(dir, "outbox.json.lock").exists(), "the flock sidecar exists")
        assertFalse(dir.resolve("outbox.json.tmp.${ProcessHandle.current().pid()}").exists())
    }

    @Test
    fun nonAsciiStaysRawUtf8() = runTest {
        outbox().put("señal académica — «así»")
        assertEquals(
            """[{"ts": 1730200000, "text": "señal académica — «así»"}]""",
            path.readText(),
            "ensure_ascii=False: no \\u escapes, both bots read the same bytes",
        )
    }

    @Test
    fun theBoxKeepsTheLastTwenty() = runTest {
        val ob = outbox()
        repeat(21) { ob.put("m$it") }
        val texts = dev.lattenero.bot.contracts.OutboxItem.Box.fromJson(
            kotlinx.serialization.json.Json.parseToJsonElement(path.readText()) as kotlinx.serialization.json.JsonArray,
        ).map { it.text }
        assertEquals((1..20).map { "m$it" }, texts, "box[-20:] — the oldest falls off")
    }

    @Test
    fun textsAreCappedToChReply() = runTest {
        outbox().put("x".repeat(5000))
        val stored = dev.lattenero.bot.contracts.OutboxItem.Box.fromJson(
            kotlinx.serialization.json.Json.parseToJsonElement(path.readText()) as kotlinx.serialization.json.JsonArray,
        ).single()
        assertEquals(CH_REPLY, stored.text.length)
    }

    @Test
    fun takeAllSwapsEverythingForAnEmptyBox() = runTest {
        val ob = outbox()
        ob.put("a")
        ob.put("b")
        val taken = ob.takeAll()
        assertEquals(listOf("a", "b"), taken?.map { it.text })
        assertEquals("[]", path.readText(), "the swap leaves [] — exactly Python's bytes")
        assertTrue(ob.takeAll()!!.isEmpty(), "the second swap gets nothing")
    }

    @Test
    fun putBackReturnsTheFailedItemsToTheFront() = runTest {
        val ob = outbox()
        ob.put("queued")
        val failed = listOf(dev.lattenero.bot.contracts.OutboxItem(ts = 5, text = "old-failure"))
        ob.putBack(failed)
        val texts = ob.takeAll()!!.map { it.text }
        assertEquals(listOf("old-failure", "queued"), texts, "remaining + box — the failed ones are the oldest")
    }

    @Test
    fun aBrokenOrMissingFileReadsAsTheDefault() = runTest {
        path.writeText("this is not json")
        outbox().put("after garbage")
        assertTrue(path.readText().endsWith(""""text": "after garbage"}]"""), "the default [] absorbed the garbage")
        val taken = outbox().takeAll()!!
        assertEquals(listOf("after garbage"), taken.map { it.text })
        assertEquals("[]", path.readText())
    }

    // ── the flock as a cross-process contract ─────────────────────────────

    /** A real child holding the POSIX lock, exactly like the Python poller would. */
    private fun lockHolder(seconds: Double): Process {
        assumeTrue(runCatching { ProcessBuilder("python3", "--version").start().waitFor() == 0 }.getOrDefault(false), "python3 needed")
        val script = """
            import fcntl, sys, time
            f = open(sys.argv[1], 'a+')
            fcntl.lockf(f, fcntl.LOCK_EX | fcntl.LOCK_NB)
            print('held', flush=True)
            time.sleep(float(sys.argv[2]))
        """.trimIndent()
        val p = ProcessBuilder("python3", "-c", script, File(dir, "outbox.json.lock").path, seconds.toString()).start()
        assertEquals("held", p.inputStream.bufferedReader().readLine(), "the child holds the lock before we proceed")
        return p
    }

    @Test
    fun theFlockIsAcquiredAfterTheHolderReleases() {
        val child = lockHolder(0.35) // released ~3 polls in
        try {
            val t0 = System.nanoTime()
            kotlinx.coroutines.runBlocking { outbox().put("waited for it") }
            val waitedS = (System.nanoTime() - t0) / 1e9
            assertTrue(waitedS >= 0.3, "we polled at Python's 100 ms cadence until the window opened")
            assertTrue(path.readText().endsWith(""""text": "waited for it"}]"""))
        } finally {
            child.destroyForcibly().waitFor()
        }
    }

    @Test
    fun theFlockDeadlineDegradesExactlyLikePythons() = runTest {
        val child = lockHolder(60.0) // holds forever (we kill it)
        val ob = Outbox(path, now = { 1_730_200_000.0 }, timeSource = testTimeSource)
        try {
            ob.put("never lands") // must NOT raise: the message is lost from the outbox but send already tried 3 times
            assertFalse(path.exists(), "nothing was written — the deadline owned the file")
            assertEquals(10_000L, testScheduler.currentTime, "the deadline is 10 s of polls at 100 ms — Python's flock budget")
            assertNull(ob.takeAll(), "the flush's swap reports 'not now' as null")
            assertEquals(
                20_000L,
                testScheduler.currentTime,
                "every update_cross_process gets its OWN 10 s budget, like Python's per-call deadline",
            )
        } finally {
            child.destroyForcibly().waitFor()
        }
    }
}
